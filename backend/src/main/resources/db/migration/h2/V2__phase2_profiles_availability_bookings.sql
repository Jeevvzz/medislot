ALTER TABLE doctor_profiles ADD COLUMN languages VARCHAR(200);

ALTER TABLE appointments ADD COLUMN duration_minutes SMALLINT NOT NULL DEFAULT 30;
ALTER TABLE appointments ADD COLUMN updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP;

CREATE TABLE doctor_availability (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  doctor_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  weekday SMALLINT NOT NULL,
  start_time TIME NOT NULL,
  end_time TIME NOT NULL,
  slot_minutes SMALLINT NOT NULL DEFAULT 30,
  active BOOLEAN NOT NULL DEFAULT TRUE,
  CONSTRAINT uq_doctor_availability_weekday UNIQUE (doctor_id, weekday),
  CONSTRAINT chk_availability_weekday CHECK (weekday BETWEEN 1 AND 7)
);

CREATE TABLE favorite_doctors (
  patient_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  doctor_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (patient_id, doctor_id)
);

CREATE TABLE appointment_slot_claims (
  doctor_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  appointment_date DATE NOT NULL,
  appointment_time TIME NOT NULL,
  appointment_id BIGINT NULL UNIQUE REFERENCES appointments(id) ON DELETE SET NULL,
  PRIMARY KEY (doctor_id, appointment_date, appointment_time)
);

INSERT INTO appointment_slot_claims (doctor_id, appointment_date, appointment_time, appointment_id)
SELECT doctor_id, appointment_date, appointment_time, id
FROM appointments
WHERE status NOT IN ('CANCELLED', 'CANCELED');

CREATE TABLE appointment_time_requests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  appointment_id BIGINT NOT NULL REFERENCES appointments(id) ON DELETE CASCADE,
  requested_by_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  requested_by_role VARCHAR(20) NOT NULL,
  proposed_date DATE NOT NULL,
  proposed_time TIME NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  decided_at TIMESTAMP
);
CREATE INDEX idx_time_request_appointment_status ON appointment_time_requests(appointment_id, status);
CREATE INDEX idx_time_request_created ON appointment_time_requests(created_at);

