CREATE TABLE prescriptions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  appointment_id BIGINT NOT NULL UNIQUE REFERENCES appointments(id),
  patient_id BIGINT NOT NULL REFERENCES users(id),
  doctor_id BIGINT NOT NULL REFERENCES users(id),
  instructions VARCHAR(2000),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE prescription_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  prescription_id BIGINT NOT NULL REFERENCES prescriptions(id) ON DELETE CASCADE,
  medicine_id BIGINT REFERENCES medicines(id),
  medicine_name VARCHAR(120) NOT NULL,
  dosage VARCHAR(200) NOT NULL,
  quantity INT NOT NULL CHECK (quantity BETWEEN 1 AND 100)
);
CREATE INDEX idx_prescription_patient ON prescriptions(patient_id,created_at);

CREATE TABLE patient_carts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  patient_id BIGINT NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE cart_items (
  cart_id BIGINT NOT NULL REFERENCES patient_carts(id) ON DELETE CASCADE,
  medicine_id BIGINT NOT NULL REFERENCES medicines(id),
  quantity INT NOT NULL CHECK (quantity BETWEEN 1 AND 100),
  PRIMARY KEY(cart_id,medicine_id)
);
CREATE TABLE medicine_orders (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  patient_id BIGINT NOT NULL REFERENCES users(id),
  order_number VARCHAR(32) NOT NULL UNIQUE,
  total DECIMAL(10,2) NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'PLACED',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE medicine_order_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id BIGINT NOT NULL REFERENCES medicine_orders(id) ON DELETE CASCADE,
  medicine_id BIGINT REFERENCES medicines(id),
  medicine_name VARCHAR(120) NOT NULL,
  unit_price DECIMAL(10,2) NOT NULL,
  quantity INT NOT NULL CHECK (quantity BETWEEN 1 AND 100)
);
CREATE INDEX idx_orders_patient_date ON medicine_orders(patient_id,created_at);

CREATE TABLE queue_tokens (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  appointment_id BIGINT NOT NULL UNIQUE REFERENCES appointments(id),
  patient_id BIGINT NOT NULL REFERENCES users(id),
  doctor_id BIGINT NOT NULL REFERENCES users(id),
  token VARCHAR(24) NOT NULL UNIQUE,
  status VARCHAR(16) NOT NULL DEFAULT 'WAITING',
  issued_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_queue_doctor_status ON queue_tokens(doctor_id,status,issued_at);
CREATE TABLE in_app_reminders (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  appointment_id BIGINT NOT NULL REFERENCES appointments(id) ON DELETE CASCADE,
  reminder_type VARCHAR(32) NOT NULL,
  title VARCHAR(180) NOT NULL,
  due_at TIMESTAMP NOT NULL,
  read_at TIMESTAMP,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_reminder_user_appointment UNIQUE(user_id,appointment_id,reminder_type)
);
CREATE INDEX idx_reminder_user_due ON in_app_reminders(user_id,due_at);
